"""Идентификатор ПОПЫТКИ выдать реквизиты — и как прочитать из него заявку.

Зачем. Montera отвечает «Такое значение поля внешний id уже существует» (422),
когда мы шлём тот же `external_id` второй раз, а слали мы ровно
`obsidian_{order_id}` — идентификатор ЗАЯВКИ. Заявка одна, попыток по ней бывает
несколько: ретрай после сетевого таймаута, эскалация, повторный заход клиента.
Вторая попытка сгорала на 422 — то есть вместо попытки мы получали минус одну
попытку, и клиент оставался без реквизитов там, где провайдер был жив.

Тот же дефект был у Lava (ключей нет, поэтому не стрелял) и у GreenPay.
У Vertu и XPay суффикс уже был, но с посекундной точностью: три быстрых ретрая
внутри одной секунды дают три одинаковых идентификатора.

Вторая половина задачи — обратный разбор, и она опаснее первой. Вебхук приносит
наш же идентификатор, по нему находится заявка. Montera и GreenPay читали его
как `split('_', 1)[1]`, то есть «всё после первого подчёркивания»: добавь суффикс
уникальности — и вебхук начнёт искать заявку с номером «1234_1783948». Оплата
придёт, а мы её не узнаем. Поэтому построение и разбор живут здесь вдвоём: одно
без другого — тихая потеря платежа.

Формат: `obsidian_{order_id}_{unique}`, где unique = миллисекунды + 3 случайных
байта. Старая форма `obsidian_{order_id}` (заявки, созданные до этого изменения,
и живые сделки у провайдеров) читается по-прежнему.
"""
from __future__ import annotations

import itertools
import os
import re
import time

# Счётчик внутри процесса. Одной только случайности мало: 500 попыток,
# уложившихся в одну миллисекунду, дали коллизию на трёх случайных байтах
# (парадокс дней рождения — 500²/2/2²⁴ ≈ 0,7 %, и это выстрелило на первом же
# прогоне теста). Счётчик делает совпадение внутри процесса невозможным, а
# случайные байты закрывают совпадение МЕЖДУ процессами — бот и relay-fastapi
# создают сделки независимо.
_seq = itertools.count(1)

PREFIX = "obsidian"

# order_id — только цифры: так формат остаётся однозначным при любом суффиксе.
_RE = re.compile(rf"^{PREFIX}_(\d+)(?:_.*)?$")


def make(order_id, prefix: str = PREFIX) -> str:
    """Уникальный идентификатор попытки по этой заявке.

    Уникальность — миллисекунды, счётчик процесса и случайные байты. Секунд не
    хватало (цикл ретраев проворачивается трижды внутри одной), одной только
    случайности — тоже: 500 попыток в одну миллисекунду столкнулись на трёх
    байтах. Счётчик снимает совпадение внутри процесса, случайность — между.
    """
    uniq = f"{int(time.time() * 1000):x}{next(_seq):x}{os.urandom(4).hex()}"
    return f"{prefix}_{order_id}_{uniq}"


def parse(external_id, prefix: str = PREFIX):
    """Идентификатор заявки из идентификатора попытки. None — если не наш.

    Понимает и старую форму без суффикса: у провайдеров могут быть живые сделки,
    созданные до появления суффикса, и их вебхуки обязаны продолжать находить
    свою заявку. Возвращается СТРОКА — так же, как возвращали прежние разборы.
    """
    if not external_id:
        return None
    m = re.match(rf"^{re.escape(prefix)}_(\d+)(?:_.*)?$", str(external_id).strip())
    return m.group(1) if m else None
