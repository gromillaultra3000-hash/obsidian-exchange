"""Сколько подтверждений делают перевод окончательным — один источник на проект.

Зачем. Приём крипты как оплаты (этап 4) упирается ровно в этот вопрос: приняв
перевод слишком рано, мы отправим клиенту свою монету за платёж, который сеть
потом отменит. Но вопрос уже стоит и без нового способа оплаты — сверка
`payout_discovery` закрывает заявку по факту «перевод в блоке», а «в блоке» и
«окончательно» это разные вещи:

  BTC/LTC   — одно подтверждение отменяется рядовым реоргом; у Litecoin блок
              раз в 2,5 минуты, и короткие развилки там обычнее, чем в Bitcoin.
  Ethereum  — до слияния переставляли по несколько блоков; биржи держат 12.
  TRON      — блок подписан SR за 3 с, но НЕОБРАТИМЫМ становится после круга
              из 19 подписей (~57 с). До этого откат — штатная ситуация сети.
  XRP/TON   — консенсус финализирует леджер сразу: подтверждение здесь одно и
              оно же окончательное. Ставить больше нечего, откатывать нечему.

Значения — общепринятые пороги бирж, а не выдумка: их же держат крупные
площадки для депозитов. Каждое переопределяется переменной окружения на случай,
если сеть поведёт себя иначе, — но НЕ вниз без причины: занижение здесь не
экономит время клиента, а переносит на нас риск сети.

Fail-closed: если про сеть ничего не известно или в записи нет числа
подтверждений — перевод НЕ окончателен. Молчание источника не должно читаться
как «всё в порядке»: цена ошибки — отправленная и невозвратная крипта.

Модуль чистый: без сети и БД.
"""
from __future__ import annotations

import os

# Порог по СЕТИ, а не по монете: USDT в TRON и USDT в Ethereum — разные риски,
# и один порог на «USDT» означал бы, что для одной из сетей он неверен.
_DEFAULTS = {
    "BTC": 2,
    "LTC": 6,
    "TRON": 19,
    "ETH": 12,
    "TON": 1,
    "XRP": 1,
}

# Монета → сеть по умолчанию, когда сеть в заявке не указана. Совпадает с
# канонической сетью выплаты: BTC/LTC — свои сети, USDT без уточнения — TRC-20.
_CANONICAL_NETWORK = {
    "BTC": "BTC",
    "LTC": "LTC",
    "USDT": "TRON",
    "ETH": "ETH",
    "TON": "TON",
    "XRP": "XRP",
}

# Как называют одну и ту же сеть в разных местах проекта.
_NETWORK_ALIASES = {
    "TRC20": "TRON", "TRC-20": "TRON", "TRX": "TRON", "TRON": "TRON",
    "ERC20": "ETH", "ERC-20": "ETH", "ETHEREUM": "ETH", "ETH": "ETH",
    "MAINNET": "", "BITCOIN": "BTC", "LITECOIN": "LTC",
    "TONCOIN": "TON", "RIPPLE": "XRP", "XRPL": "XRP",
}


def normalize_network(currency=None, network=None) -> str:
    """Каноническое имя сети. Пусто — если определить нечем.

    Сеть из заявки важнее валюты: у USDT их две, и подменять указанную сеть
    канонической значило бы судить перевод по чужому порогу.
    """
    net = str(network or "").strip().upper()
    net = _NETWORK_ALIASES.get(net, net)
    if net in _DEFAULTS:
        return net
    cur = str(currency or "").strip().upper()
    return _CANONICAL_NETWORK.get(cur, "")


def required_confirmations(currency=None, network=None):
    """Порог окончательности для сети. None — сеть неизвестна, судить нечем.

    None и 0 здесь принципиально разные ответы: 0 значил бы «подтверждений не
    нужно», а мы хотим сказать «мы не знаем эту сеть» — и вызывающий обязан
    отказать, а не принять.
    """
    net = normalize_network(currency, network)
    if not net:
        return None
    raw = os.getenv(f"CONFIRMATIONS_{net}", "").strip()
    if raw:
        try:
            value = int(raw)
            if value >= 1:
                return value
            # 0 и отрицательные игнорируем молча не будем: это попытка
            # выключить защиту переменной окружения, и она не должна
            # получиться незаметно.
            raise ValueError(f"CONFIRMATIONS_{net}={raw}: порог меньше одного")
        except ValueError as e:
            if "порог меньше одного" in str(e):
                raise
            # Нечисловое значение — как будто его нет: правило по умолчанию
            # безопаснее сломанной настройки.
    return _DEFAULTS[net]


def confirmations_of(record) -> int:
    """Число подтверждений из записи о переводе. Нет числа → -1.

    -1, а не 0: «ноль подтверждений» — это известный факт про перевод в
    мемпуле, а -1 говорит «источник не сообщил», и это разные основания для
    отказа. Флаг `confirmed` в число НЕ превращаем: он означает лишь «попал в
    блок», то есть ровно одно подтверждение или неизвестно сколько.
    """
    if not isinstance(record, dict):
        return -1
    value = record.get("confirmations")
    if value is None:
        return -1
    try:
        n = int(value)
    except (TypeError, ValueError):
        return -1
    return n if n >= 0 else -1


def is_final(record, currency=None, network=None) -> bool:
    """Можно ли считать перевод состоявшимся окончательно. Fail-closed.

    Отдельно про сети с порогом 1: там флага `confirmed` достаточно — «в блоке»
    и «окончательно» для них одно и то же. Для остальных нужен именно счётчик:
    у сети с порогом 12 флаг «в блоке» не говорит ничего о том, двенадцать
    подтверждений или одно.
    """
    if not isinstance(record, dict):
        return False
    # Явное «не в блоке» перевешивает любой счётчик. Запись, где сказано
    # confirmed=False и при этом подтверждений шесть, противоречива, а
    # противоречие в денежном гейте читается в сторону отказа. Отсутствие
    # ключа — не то же самое, что False: часть источников его не ставит.
    if "confirmed" in record and not record["confirmed"]:
        return False
    # Сама цепь сказала «откатить нельзя» — это сильнее любого счётчика.
    # Ставить этот флаг вправе ТОЛЬКО читатель, который получил утверждение от
    # источника (у TRON — выборка `only_confirmed=true`, то есть несократимые
    # блоки). Вывести его из времени, возраста или «наверное, уже прошло»
    # нельзя: тогда флаг станет вторым, домашним правилом окончательности —
    # ровно тем, ради отмены которого этот модуль и написан.
    if record.get("irreversible") is True:
        return True
    need = required_confirmations(currency, network)
    if need is None:
        return False
    have = confirmations_of(record)
    if have >= 0:
        return have >= need
    return need <= 1 and bool(record.get("confirmed"))


def finality_note(record, currency=None, network=None) -> str:
    """Человекочитаемая причина отказа — для журнала и карточки оператора."""
    if isinstance(record, dict) and record.get("irreversible") is True:
        return "цепь объявила перевод несократимым — окончательно"
    need = required_confirmations(currency, network)
    if need is None:
        return f"сеть не распознана ({currency}/{network}) — порог неизвестен"
    have = confirmations_of(record)
    if have < 0:
        if need <= 1:
            return ("источник не сообщил подтверждений; сеть финализирует "
                    "сразу, решаем по флагу «в блоке»")
        return f"источник не сообщил число подтверждений, нужно {need}"
    if have >= need:
        return f"подтверждений {have} из {need} — окончательно"
    return f"подтверждений {have} из {need} — ещё не окончательно"
