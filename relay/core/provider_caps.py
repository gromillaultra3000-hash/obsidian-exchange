"""Что провайдер УМЕЕТ нам сообщить — и чего от него ждать бесполезно.

Зачем. Трейдер на стороне провайдера может попросить у клиента доп. проверку —
видео перевода или PDF-чек. У Montera для этого есть вебхук: запрос долетает до
нас, клиент получает сообщение с кнопкой, всё работает. У Vertu такого канала
НЕТ — ни вебхука, ни поля в статусе сделки; трейдер пишет это в телеграм-чат
диспута, который не читает никто. Клиент ждёт, сделка истекает, деньги остаются
у трейдера. Так висели 22 заявки на 99 400 ₽.

Кодом канал не создать — его нет у провайдера. Единственное, что можно сделать
честно: не притворяться, что он есть. Здесь записано, кто что умеет, и это знание
попадает в уведомление персоналу: «у этого провайдера запрос доп. проверки к нам
не приходит — если сделка умерла, ищите причину в ИХ кабинете».

Правило по умолчанию — fail-closed: незнакомый провайдер считается НЕумеющим.
Ошибиться в эту сторону значит лишний раз позвать человека; ошибиться в другую —
молча ждать сигнала, которого не будет.
"""
from __future__ import annotations

# Провайдер → доходит ли до нас запрос трейдера на доп. проверку.
# True ставится только там, где это ПРОВЕРЕНО живым трафиком.
_VERIFICATION_CHANNEL = {
    # Вебхук /montera/webhook с requested_type video|pdf-success — подтверждён
    # живыми запросами: клиент получает сообщение с кнопкой и присылает файл.
    "montera": True,
    # Опрос статуса отдаёт только Pending/Approved/Declined/Revoked. Просьбы
    # трейдера живут в телеграм-чате диспута — до системы не доходят.
    "vertu": False,
    # Merchant Integration API: у инвойса есть спор (open_dispute), но входящего
    # уведомления «трейдер просит видео» в нём нет.
    "brabus": False,
    "stormtrade": False,
    "fallback": False,      # это тот же Brabus в другом варианте
    "greenpay": False,
    "lava": False,
    "xpay": False,
    # В payment_sessions лежит «xpay», но имя модуля/класса — xpayconnect.
    # Оба варианта ведут к одному ответу: гадать, каким именем позвали, —
    # ровно тот способ, каким провайдер тихо проваливается в умолчание.
    "xpayconnect": False,
}


def _key(provider) -> str:
    """Имя провайдера из того вида, в каком оно лежит в payment_sessions.

    Там встречается и «brabus:tbank_deeplink» — вариант через двоеточие.
    Вариант канала не меняет, поэтому берём часть до двоеточия.
    """
    return str(provider or "").strip().lower().split(":", 1)[0]


def has_verification_channel(provider) -> bool:
    """Дойдёт ли до нас просьба трейдера о доп. проверке. Неизвестный — нет."""
    return _VERIFICATION_CHANNEL.get(_key(provider), False)


def verification_note(provider) -> str:
    """Строка для персонала: чего ждать от этого провайдера, а чего не ждать."""
    name = _key(provider) or "провайдер"
    if has_verification_channel(provider):
        return (f"У {name} запрос доп. проверки приходит вебхуком — клиент уже "
                f"получил сообщение с кнопкой, отдельно делать ничего не нужно.")
    return (f"⚠️ У {name} канала для запроса доп. проверки НЕТ: если трейдер "
            f"просил видео или PDF, до нас это не дошло и не дойдёт. Смотреть "
            f"в кабинете/чате провайдера и решать вручную.")
