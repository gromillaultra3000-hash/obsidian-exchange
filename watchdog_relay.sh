#!/bin/bash
# Сторож боевого сайта/API: поднять relay-fastapi, если он умер или завис.
#
# ⚠️ Раньше этот скрипт сторожил exchange-relay — легаси-ретранслятор
# (relay/app.py, :5000). Его выключили и disable'нули 19.07.2026: его фоновый
# поток убивал платёжные сессии на 15-й минуте из 30, из-за чего клиент терял
# кнопку «я оплатил» (260 сессий из 426 за месяц). А сторож, работая по крону
# каждые 30 минут, 21.07 просто ПОДНЯЛ его обратно — и он проработал ещё
# шесть дней. Инфраструктура спорила сама с собой: одна рука выключает,
# другая включает, и никто об этом не знает.
#
# Теперь сторожим то, что действительно обслуживает клиентов.

STATE=/run/obsidian-watchdog-relay
LOG=/root/watchdog.log

restart() {
    echo "$(date -Is): relay-fastapi перезапущен ($1)" >> "$LOG"
    systemctl restart relay-fastapi
}

if ! systemctl is-active --quiet relay-fastapi; then
    restart "сервис не активен"
    exit 0
fi

# Живость по эндпоинту, а не только по статусу юнита: процесс может быть жив и
# при этом не отвечать (заблокированный event loop выглядит как «active»).
if ! curl -s --max-time 10 -o /dev/null http://127.0.0.1:5001/api/system-status; then
    # Один неответ может быть случайностью (деплой перезапускает сервис).
    # Перезапускаем со второго подряд — состояние переживает запуски скрипта.
    if [ -f "$STATE" ]; then
        rm -f "$STATE"
        restart "не отвечает два раза подряд"
    else
        touch "$STATE"
    fi
else
    rm -f "$STATE"
fi
